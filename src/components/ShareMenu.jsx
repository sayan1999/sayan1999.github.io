export default function ShareMenu({ slug, title }) {
  const [open, setOpen] = useState(false)
  const [copied, setCopied] = useState(false)
  const wrapRef = useRef(null)

  const shareUrl = window.location.origin + '/post/' + slug + '/'

  function toggle() {
    setOpen(v => !v)
  }

  function close() {
    setOpen(false)
  }

  function shareWA() {
    window.open('https://wa.me/?text=' + encodeURIComponent(title + ' ' + shareUrl), '_blank', 'noopener')
    close()
  }

  function shareX() {
    window.open(
      'https://twitter.com/intent/tweet?text=' + encodeURIComponent(title) + '&url=' + encodeURIComponent(shareUrl),
      '_blank', 'noopener'
    )
    close()
  }

  function shareReddit() {
    window.open(
      'https://reddit.com/submit?url=' + encodeURIComponent(shareUrl) + '&title=' + encodeURIComponent(title),
      '_blank', 'noopener'
    )
    close()
  }

  function shareIG() {
    copyLink()
  }

  function copyLink() {
    navigator.clipboard.writeText(shareUrl).then(() => {
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    })
    close()
  }

  // Close on outside click
  useEffect(() => {
    function onDocClick(e) {
      if (!wrapRef.current?.contains(e.target)) setOpen(false)
    }
    document.addEventListener('click', onDocClick)
    return () => document.removeEventListener('click', onDocClick)
  }, [])

  return (
    <div className="share-wrap" ref={wrapRef}>
      <button className="share-btn" onClick={toggle}>
        {SVG_SHARE} share
      </button>
      <div className={`share-menu${open ? ' open' : ''}`}>
        <button className="share-icon whatsapp" title="WhatsApp" onClick={shareWA}>{SVG_WA}</button>
        <button className="share-icon twitter" title="X / Twitter" onClick={shareX}>{SVG_X}</button>
        <button className="share-icon reddit" title="Reddit" onClick={shareReddit}>{SVG_REDDIT}</button>
        <button className="share-icon instagram" title="Instagram (copies link)" onClick={shareIG}>{SVG_IG}</button>
        <div className="share-divider"></div>
        <button className="share-icon copylink" title="Copy link" onClick={copyLink}>{SVG_LINK}</button>
        <span className="share-copied" style={{ display: copied ? 'inline' : 'none' }}>copied!</span>
      </div>
    </div>
  )
}
